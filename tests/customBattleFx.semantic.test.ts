assert.equal(customFxPhase('extra',10,48,[]).buff,true);
const pre=customFxPhase('sa',57,96,[58]),hit=customFxPhase('sa',58,96,[58]);
assert.equal(pre.afterHit,false);assert.equal(hit.afterHit,true);assert.equal(hit.travel,1);assert.equal(hit.impact,0);
assert.equal(customFxPhase('ultimate',72,120,[72]).ultimate,true);
assert.equal(customFxPhase('sa',10,96,[20,50]).hit,20);
assert.equal(customFxPhase('sa',21,96,[20,50]).hit,20);
