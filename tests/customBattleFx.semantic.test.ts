assert.equal(customFxPhase('sa',58,96,[58],46).travel,1);
assert.equal(customFxPhase('sa',3,12,[8],0).launch,0,'允許從第零幀開始發射');
const melee={style:'vortex' as const,color:'#224432',secondary:'#8bd8a0',melee:true,meleeSequences:['attack','ultimate']};
assert.equal(isMeleePresentationSequence(melee,'ultimate'),true,'近身第五技能必須走同一套接近對手的路徑');
assert.equal(isMeleePresentationSequence(melee,'sa'),false,'發令型特攻不被誤判為近身');
