import assert from 'node:assert/strict';
import React,{act} from 'react';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost/'});
Object.assign(globalThis,{Event:dom.window.Event,window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,HTMLElement:dom.window.HTMLElement,IS_REACT_ACT_ENVIRONMENT:true});
Object.defineProperty(globalThis,'navigator',{configurable:true,value:dom.window.navigator});
const {createRoot}=await import('react-dom/client'),root=createRoot(document.getElementById('root')!);
const server=await createServer({server:{middlewareMode:true,hmr:false,watch:null},appType:'custom',logLevel:'silent'});
const settle=(ms:number)=>act(async()=>{await new Promise(r=>setTimeout(r,ms));});
try{
 const {ChainImage,ElfAvatar}=await server.ssrLoadModule('/src/components/SeerImages.tsx');
 const {ImageRetrySetting}=await server.ssrLoadModule('/src/components/ImageRetrySetting.tsx');
 const settings=await server.ssrLoadModule('/src/utils/imageRetrySettings.ts');
 const render=(url:string)=>act(async()=>root.render(<><ImageRetrySetting/><div id="picture"><ChainImage urls={[url]} fallback={<img src="/elf-art/unknown_myth_ghost_body.png" alt="備用圖"/>}/></div></>));
 const fail=()=>act(async()=>document.querySelector('#picture img')!.dispatchEvent(new dom.window.Event('error',{bubbles:true})));
 await act(async()=>settings.writeImageRetryMode('manual'));await render('/manual.png');await fail();
 assert.equal(document.querySelector('#picture img')!.getAttribute('alt'),'備用圖');
 await act(async()=>window.dispatchEvent(new dom.window.Event('focus')));
 assert.equal(document.querySelector('#picture img')!.getAttribute('alt'),'備用圖','手動模式不因切回視窗重試');
 await act(async()=>document.querySelector('#picture img')!.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true})));
 assert.equal(document.querySelector('#picture img')!.getAttribute('src'),'/manual.png','點擊備用圖重試原圖');
 await act(async()=>settings.writeImageRetryMode('off'));await render('/off.png');await fail();
 await act(async()=>{document.querySelector('#picture img')!.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true}));window.dispatchEvent(new dom.window.Event('online'));});
 assert.equal(document.querySelector('#picture img')!.getAttribute('alt'),'備用圖','不重試模式忽略點擊與網路恢復');
 await act(async()=>settings.writeImageRetryMode('auto'));await render('/auto.png');await fail();
 await settle(8250);
 assert.equal(document.querySelector('#picture img')!.getAttribute('src'),'/auto.png','自動重試不需要重新開啟介面');
 await act(async()=>document.querySelector('#picture img')!.dispatchEvent(new dom.window.Event('load')));
 assert.equal((document.querySelector('[aria-label="圖片重試方式"]') as HTMLSelectElement).value,'auto');
 await act(async()=>settings.writeImageRetryMode('off'));
 const elf:any={id:'no-art',name:'測試無圖精靈',skills:[],path:'/missing-body.png'};
 await act(async()=>root.render(<ElfAvatar elf={elf} kind="body"/>));await settle(80);
 for(let i=0;i<12&&!document.querySelector('img')?.src.includes('unknown_myth_ghost_body');i++)await act(async()=>document.querySelector('img')?.dispatchEvent(new dom.window.Event('error')));
 assert.ok(document.querySelector('img')?.src.includes('unknown_myth_ghost_body'),'全身圖失敗顯示未知全身立繪，不縮成圓形頭像');
 await act(async()=>root.render(<ElfAvatar elf={{...elf,isConcealed:true}} battleSide="p2" kind="head"/>));
 assert.ok(document.querySelector('img')?.src.includes('unknown_myth_ghost_head'),'隱匿頭像統一未知立繪');
 console.log('圖片手動／自動／不重試、點擊、焦點、斷線恢復與設定連動通過');
}finally{await act(async()=>root.unmount());await server.close();dom.window.close();}
