// 工作區整理工具：預覽不動檔；--apply 只搬移明列項目；24 小時內修改、Git 追蹤、未分類、舊副本（未加旗標）不動；--restore 原路搬回。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tidy-'));
const proj = path.join(tmp, 'proj');
fs.mkdirSync(path.join(proj, 'scripts'), { recursive: true });
fs.copyFileSync('scripts/workspace_tidy.mjs', path.join(proj, 'scripts', 'workspace_tidy.mjs'));
const old = Date.now() / 1000 - 3 * 86400;
const mk = (p, recent = false) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, 'x'); if (!recent) fs.utimesSync(p, old, old); };
mk(path.join(tmp, 'seer-site-20261105.zip'));
mk(path.join(tmp, '給Claude的提示詞.txt'));
mk(path.join(tmp, '_dom.html'));
mk(path.join(tmp, 'dsh-restart-20261121.log'), true);
mk(path.join(tmp, 'package.json'));
mk(path.join(tmp, '神秘檔.txt'));
mk(path.join(proj, '_u_breakdown.json'));
mk(path.join(proj, 'preview-server.log'));
execFileSync('git', ['init', '-q'], { cwd: proj });
execFileSync('git', ['add', 'preview-server.log'], { cwd: proj });
const run = (...a) => execFileSync(process.execPath, ['scripts/workspace_tidy.mjs', ...a], { cwd: proj, encoding: 'utf8' });
const preview = run();
assert.match(preview, /預覽：可搬移 4 項/, preview);
assert.ok(fs.existsSync(path.join(tmp, 'seer-site-20261105.zip')), '預覽不動檔');
const out = run('--apply');
assert.ok(fs.existsSync(path.join(tmp, '_發佈封存', 'seer-site-20261105.zip')));
assert.ok(fs.existsSync(path.join(tmp, '_參考資料', '給Claude的提示詞.txt')));
assert.ok(fs.readdirSync(path.join(tmp, '_封存')).some(d => fs.existsSync(path.join(tmp, '_封存', d, '_dom.html'))));
assert.ok(fs.existsSync(path.join(tmp, 'dsh-restart-20261121.log')), '24 小時內修改不搬');
assert.ok(fs.existsSync(path.join(tmp, 'package.json')), '舊副本未加旗標不搬');
assert.ok(fs.existsSync(path.join(tmp, '神秘檔.txt')), '未分類不搬');
assert.ok(fs.existsSync(path.join(proj, 'preview-server.log')), 'Git 追蹤不搬');
assert.ok(!fs.existsSync(path.join(proj, '_u_breakdown.json')), '專案零散檔搬走');
const manifest = out.match(/--restore "([^"]+)"/)[1];
run('--restore', manifest);
for (const f of ['seer-site-20261105.zip', '給Claude的提示詞.txt', '_dom.html']) assert.ok(fs.existsSync(path.join(tmp, f)), `還原 ${f}`);
assert.ok(fs.existsSync(path.join(proj, '_u_breakdown.json')));
fs.rmSync(tmp, { recursive: true, force: true });
console.log('workspaceTidy passed');
