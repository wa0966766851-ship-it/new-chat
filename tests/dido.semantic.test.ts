import assert from 'node:assert/strict';
import {createHarness} from './helpers/migrationHarness';
const h=await createHarness();
try{
 const {DEFAULT_ELVES}=await h.server.ssrLoadModule('/src/data/defaultElvesLoaded.ts');
 const {kitEntryIssue}=await h.server.ssrLoadModule('/src/effects/effectConnection.ts');
 const e=DEFAULT_ELVES.find((e:any)=>e.id==='5055');assert.ok(e);
 const {authoredEntry:entry,actions:act,operation:op}=await h.server.ssrLoadModule('/src/data/authoredKitTools.ts');
 const {DIDO_FIELDS}=await h.server.ssrLoadModule('/src/data/dido.ts');
 for(const d of [e.soulMark,...e.skillPool])for(const k of d.kit)assert.equal(kitEntryIssue(k),null,d.name+': '+k.customText);
 for(const side of ['p1','p2'] as const){
  const fighter=(skills:any[])=>h.unit('5055',1000,skills,{maxHp:4000,extra:{name:e.name,soulMark:e.soulMark}});
  const [pool]=await h.play(side,{self:fighter([h.wait()]),opp:h.unit('target',20000,[h.wait()]),turns:()=>['pass','pass']});
  assert.equal(pool.self.currentHp,2300,'己方泳館回血1300');
  assert.equal(pool.opp.currentHp,20000,'不恢復對方');
  assert.equal(pool.state[`${side}RegistryState`].teamSideField.name,'靈籟泳館');
  const cap=h.find('5055','靈籟之願');
  const harm=h.kitSkill('兩次技能附傷與真傷',[{op:'no_heal',p:{turns:3}},...Array.from({length:2},()=>({op:'dmg',p:{type:'技能',flat:800,elem:'普通'}})),{op:'dmg',p:{type:'真實',flat:333}}]);
  const immune={name:'測試異常免疫',effectMode:'kit',kit:[entry('免疫異常','entrance',[act(op('immune_status_perm'))],0,'soulmark')]};
  const limited=await h.play(side,{self:h.unit('cap',1000,[cap],{speed:200}),opp:h.unit('target',20000,[harm],{extra:{soulMark:immune}}),turns:(_engine,t)=>t===1?[0,'pass']:['pass',0]},2);
  assert.equal(limited[1].self.currentHp,167,'每筆各250，真傷333不受限制；不是整回合累計250');
  const outCap=h.find('5055','時空牽絆');
  const [outLimited]=await h.play(side,{self:h.unit('out-cap',1000,[outCap],{speed:200}),opp:h.unit('target',20000,[harm],{statStages:{atk:1},extra:{soulMark:immune}}),turns:()=>[0,0]});
  assert.equal(outLimited.opp.statStages.atk,0,'確實清除對手強化');
  assert.equal(outLimited.self.currentHp,167,'清除成功後限制對手每筆造成的技能傷害，真傷不受限制');
  const conversion=h.find('5055','琴.萬律歸一');
  const harmAndTrue=h.kitSkill('技能附傷與真傷',[...Array.from({length:2},()=>({op:'dmg',p:{type:'技能',flat:800,elem:'普通'}})),{op:'dmg',p:{type:'真實',flat:333}}],{category:'特殊',power:0});
  const [converted]=await h.play(side,{self:h.unit('conversion',400,[conversion],{maxHp:1000,speed:200,statStages:{def:-1}}),opp:h.unit('target',20000,[harmAndTrue]),turns:()=>[0,0]});
  assert.equal(converted.self.currentHp,667,'技能傷害轉恢復，真實傷害仍扣除333');
  assert.equal(converted.self.statStages.def,2,'反轉下降後再提升防禦');
  const reserve=h.find('5055','幻夢芳逝');
  const sacrifice=await h.play(side,{self:h.unit('sacrifice',1000,[reserve],{speed:200}),selfBench:[h.unit('recipient',1000,[h.wait()])],opp:h.unit('target',20000,[h.wait()]),turns:(_engine,t)=>t===1?[0,'pass']:[{switch:1},'pass']},2);
  assert.equal(sacrifice[0].self.currentHp,0,'備選技能消耗全部體力');
  assert.equal(sacrifice[1].self.id,'recipient');assert.equal(sacrifice[1].self.currentHp,13);
  assert.equal(sacrifice[1].self.shield,1300);assert.equal(sacrifice[1].self.barrier,1300);
  const fatal=h.kitSkill('多次致死',[{op:'no_heal',p:{turns:5}},...Array.from({length:3},()=>({op:'dmg',p:{type:'真實',flat:99999}}))]);
  const held=await h.play(side,{self:fighter([h.wait()]),opp:h.unit('fatal',20000,[fatal]),turns:()=>['pass',0]},2);
  assert.equal(held[0].self.currentHp,13,'同回合多次致死都保留13');
  assert.equal(held[1].self.currentHp,0,'下回合不會重新取得本次在場首次存活');
  const reentered=await h.play(side,{self:fighter([h.wait()]),selfBench:[h.unit('relay',4000,[h.wait()])],opp:h.unit('fatal',20000,[fatal]),
   turns:(_engine,t)=>t===2?[{switch:1},'pass']:t===3?[{switch:0},0]:['pass',0]},4);
  assert.equal(reentered[0].self.currentHp,13,'第一次登場後的首次致死');
  assert.equal(reentered[1].self.id,'relay');
  assert.equal(reentered[2].self.id,'5055');assert.equal(reentered[2].self.currentHp,13,'再次登場重新取得首次致死保留，場地已有其他效果也會重置');
  assert.equal(reentered[3].self.currentHp,0,'再次登場的保留亦只到該回合結束，不是每回合重置');
  const fifth=h.find('5055','朵·盛夏詠嘆');
  const swapped=await h.play(side,{self:fighter([fifth]),opp:h.unit('target',20000,[h.wait()]),turns:(_engine,t)=>t===1?[0,'pass']:['pass','pass']},2);
  assert.equal(swapped[0].self.shield,2600);assert.equal(swapped[0].self.barrier,1300);
  assert.equal(swapped[0].state[`${side}RegistryState`].teamSideField.id,DIDO_FIELDS.pool.id,'本回合不提前切場');
  assert.equal(swapped[1].state[`${side}RegistryState`].teamSideField.id,DIDO_FIELDS.stage.id,'下回合才切換己方場地');
  assert.equal(swapped[1].self.skills[0].pp,5,'舞台恢復所有技能5PP，受上限限制');
  const strike={...h.wait(),name:'低命中攻擊',category:'物理',power:90,accuracy:0,isSureHit:false};
  const [sure]=await h.play(side,{self:fighter([strike]),opp:h.unit('target',20000,[h.wait()]),turns:()=>[0,'pass']});
  assert.ok(sure.opp.currentHp<20000,'泳館令0命中技能也必定命中');
  const stageSoul={name:'獨立場地測試',effectMode:'kit',kit:[entry('設定場地','entrance',[act(op('side_field_set',{field:DIDO_FIELDS.stage}))],0,'soulmark')]};
  const attack={...strike,accuracy:100,isSureHit:true};
  const [base]=await h.play(side,{self:h.unit('base',4000,[attack]),opp:h.unit('target',20000,[h.wait()]),turns:()=>[0,'pass']});
  const [boosted]=await h.play(side,{self:h.unit('boosted',4000,[attack],{extra:{soulMark:stageSoul}}),opp:h.unit('target',20000,[h.wait()]),turns:()=>[0,'pass']});
  const baseDamage=20000-base.opp.currentHp,stageDamage=20000-boosted.opp.currentHp;
  assert.ok(Math.abs(stageDamage-baseDamage*14)<=14,'舞台提升1300%為14倍攻擊傷害');
  const bench=h.unit('ally',1000,[{...h.wait(),pp:0}],{maxHp:4000});
  const departed=await h.play(side,{self:fighter([h.wait()]),selfBench:[bench],opp:h.unit('target',20000,[h.wait()]),turns:(_engine,t)=>t===1?['pass','pass']:[{switch:1},'pass']},2);
  assert.equal(departed[1].self.id,'ally');assert.equal(departed[1].self.currentHp,3600,'場下已恢復1300，登場後再恢復1300');
  assert.equal(departed[1].state[`${side}RegistryState`].teamSideField.expiresRound,14,'第2回合刷新至第14回合，最後一回合雙方結算仍有效');
  assert.ok(departed[1].state[`${side}Timers`].some((t:any)=>t.id==='next-skill-properties'&&t.remaining===3),'下隻取得3次技能先手與必中');
  const own=side==='p1'?'p2':'p1';assert.equal(departed[1].state[`${own}RegistryState`].teamSideField,undefined,'不刷新對手場地');
 }
 console.log('蒂朵：雙方逐次250上限、真傷排除、13體力致死窗口、下回合切場、離場刷新與隊友交付通過');
}finally{await h.close();}
