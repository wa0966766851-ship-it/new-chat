import assert from 'node:assert/strict';
import React,{act,useState} from 'react';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';
import {BattlePresentation} from '../src/battle/presentation';
import {DEFAULT_BATTLE_ANIMATION,effectiveAnimationSettings,readAnimationSettings,BATTLE_ANIMATION_KEY} from '../src/battle/animationSettings';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost:3000',pretendToBeVisual:true});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,HTMLElement:dom.window.HTMLElement,Element:dom.window.Element,IS_REACT_ACT_ENVIRONMENT:true});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
globalThis.fetch=(async()=>{throw Error('offline UI fixture');}) as any;
const {createRoot}=await import('react-dom/client');
const root=createRoot(document.getElementById('root')!);
const server=await createServer({server:{middlewareMode:true,hmr:false,watch:null},appType:'custom',logLevel:'silent'});
try{
 const {loadSeerIndex}=await server.ssrLoadModule('/src/battle/seerAssets.ts');await loadSeerIndex();
 const {default:ControlHubPanel}=await server.ssrLoadModule('/src/components/ControlHubPanel.tsx');
 function Settings(){const [animationSettings,setAnimationSettings]=useState({...DEFAULT_BATTLE_ANIMATION,extra:false});return <ControlHubPanel {...{activeTab:'battle',state:{},localResources:{},currentScene:'start',backgrounds:[],playlist:[],animationSettings,setAnimationSettings,updateUrlParam:()=>{}} as any}/>;}
 await act(async()=>root.render(<Settings/>));
 const toggle=document.querySelector<HTMLInputElement>('[aria-label="靜態模式"]')!;assert.ok(toggle);
 await act(async()=>toggle.click());
 const raw=readAnimationSettings();assert.equal(raw.staticMode,true);assert.equal(raw.skill,true);assert.equal(raw.extra,false);
 const inputs=[...document.querySelectorAll<HTMLInputElement>('[data-testid="battle-animation-settings"] input')];assert.equal(inputs.length,6);
 assert.deepEqual(inputs.map(e=>e.disabled),[true,false,false,false,false,true],'靜態模式只鎖出招動畫與入戰動畫，飄字開關仍可調');
 const enabled=effectiveAnimationSettings(raw);assert.ok(['skill','intro'].every(k=>!(enabled as any)[k]),'靜態模式關閉位移與特效');
 assert.ok(['damage','potion','roundEnd'].every(k=>(enabled as any)[k]===(raw as any)[k]),'飄字開關照使用者設定保留');assert.equal(enabled.extra,false,'使用者本來就關的額外行動維持關閉');
 let popupCount=0;const playback=new BattlePresentation(()=>{popupCount+=playback.popups.length;},()=>false,()=>raw);
 await playback.record({side:'p1',elfId:'a',type:'skill',amount:30,delta:-30,before:100,after:70,maxHp:100});
 await playback.record({side:'p1',elfId:'a',type:'true',amount:10,delta:-10,before:70,after:60,maxHp:100});await playback.flush();
 assert.ok(popupCount>=2,'靜態模式保留傷害飄字（技能傷害與真實傷害）');assert.equal(playback.hp.get('p1:a'),60,'靜態模式仍完整同步結算體力');assert.equal(playback.shakeSide,null,'靜態模式也略過受擊晃動');playback.dispose();
 await act(async()=>toggle.click());assert.equal(readAnimationSettings().staticMode,false);assert.equal(readAnimationSettings().extra,false);assert.equal(readAnimationSettings().skill,true);
 assert.ok(!document.querySelector<HTMLInputElement>('[data-testid="battle-animation-settings"] input')!.disabled);
 assert.ok(localStorage.getItem(BATTLE_ANIMATION_KEY));
 const {DEFAULT_ELVES}=await server.ssrLoadModule('/src/data/defaultElvesLoaded.ts');
 const elf=DEFAULT_ELVES.find((e:any)=>e.id==='7070');
 const {ElfCardSheet}=await server.ssrLoadModule('/src/shell/art/ElfCardSheet.tsx');
 localStorage.setItem('seer_featured_elf','keep');
 await act(async()=>root.render(<ElfCardSheet elf={elf} onClose={()=>{}}/>));
 assert.equal(document.querySelector('.elf-spotlight')?.getAttribute('aria-label'),'精靈介紹');
 assert.equal(document.querySelectorAll('.spot-skills article').length,5);
 assert.ok(!document.querySelector('.elf-spotlight')?.textContent?.includes('新精靈'));assert.equal(localStorage.getItem('seer_featured_elf'),'keep');
 const {BagScene}=await server.ssrLoadModule('/src/shell/scenes/BagScene.tsx');
 const noop=()=>{};const bridge:any={allElves:[elf],allElvesCombined:[elf],p1Team:[],p2Team:[],setView:noop,setEditingElf:noop,setShowEncyclopedia:noop};
 await act(async()=>root.render(<BagScene b={bridge}/>));
 const elfTab=[...document.querySelectorAll('button')].find(e=>e.textContent?.trim()==='精靈');assert.ok(elfTab);await act(async()=>elfTab.click());
 const detail=document.querySelector<HTMLButtonElement>(`button[title="查看 ${elf.name} 的精靈介紹"]`);assert.ok(detail);await act(async()=>detail.click());
 assert.equal(document.querySelector('.elf-spotlight')?.getAttribute('aria-label'),'精靈介紹');assert.equal(document.querySelectorAll('.spot-skills article').length,5);
 assert.equal(document.querySelector('[aria-label="物品詳情"]'),null,'精靈不能導向裝備的簡易抽屜');
 console.log('控制中心靜態模式切換／保存／偏好恢復、跳字略過與體力同步、背包共用介紹模板通過');
}finally{await act(async()=>root.unmount());await server.close();dom.window.close();}
