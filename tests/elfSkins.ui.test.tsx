import assert from 'node:assert/strict';
import React,{act} from 'react';
import {JSDOM} from 'jsdom';
import {ElfSkinPicker} from '../src/components/ElfSkinPicker';
import {ElfAvatar} from '../src/components/SeerImages';
import {availableElfSkins} from '../src/data/elfSkins';
import {appearanceElf} from '../src/battle/illusionPresentation';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,IS_REACT_ACT_ENVIRONMENT:true});
const {createRoot}=await import('react-dom/client');
const root=createRoot(document.getElementById('root')!);
let elf:any={id:'5029',name:'異境神霆·雷伊',path:'otherworld_thunder_rey',currentHp:42,skills:[{name:'不改動',pp:2}],soulMark:{name:'異'},calculatedStats:{atk:77}};
const before=structuredClone(elf);
const render=()=>root.render(<><ElfSkinPicker elf={elf} onChange={next=>{elf=next;render();}} /><ElfAvatar elf={elf} kind="body" battleSide="p1" /><ElfAvatar elf={elf} kind="body" battleSide="p2" /></>);
try{
 await act(async()=>render());
 const select=document.querySelector('select')!;
 await act(async()=>{select.value='rey-thunder-dragon-v1';select.dispatchEvent(new dom.window.Event('change',{bubbles:true}));});
 assert.equal(elf.skinId,'rey-thunder-dragon-v1');
 assert.deepEqual({...elf,skinId:undefined},{...before,skinId:undefined},'皮膚不能動到戰鬥資料');
 const imgs=[...document.querySelectorAll('img')].filter(i=>i.getAttribute('src')?.includes('/elf-skins/'));
 assert.equal(imgs.length,3);assert.equal(imgs[1].style.transform,'');assert.equal(imgs[2].style.transform,'scaleX(-1)');
 assert.equal(JSON.parse(JSON.stringify(elf)).skinId,elf.skinId);
 await act(async()=>{select.value='rey-original';select.dispatchEvent(new dom.window.Event('change',{bubbles:true}));});
 assert.equal(elf.skinId,'rey-original');
 const originalImgs=[...document.querySelectorAll('img')].filter(i=>i.getAttribute('src')==='/seer/body/70.png');
 assert.equal(originalImgs.length,3);assert.equal(originalImgs[1].style.transform,'scaleX(-1)');assert.equal(originalImgs[2].style.transform,'');
 assert.equal(JSON.parse(JSON.stringify(elf)).skinId,'rey-original');
 const illusion=appearanceElf({...before,skinId:'old',illusion:{target:elf} as any});assert.equal(illusion.skinId,elf.skinId);
 assert.equal(availableElfSkins({id:'7070',name:'魔化.雷伊'}).length,2);
 await act(async()=>{select.value='';select.dispatchEvent(new dom.window.Event('change',{bubbles:true}));});
 assert.equal(elf.skinId,undefined);assert.equal(elf.path,before.path);
 assert.equal(document.querySelectorAll('img[src*="/elf-skins/"]').length,0);
 await act(async()=>root.render(<ElfAvatar elf={{...elf,skinId:'rey-original'}} kind="head" battleSide="p1"/>));
 assert.equal(document.querySelector('img')?.getAttribute('src'),'/seer/head/70.png','普通皮膚頭像不可沿用異境雷伊');
 assert.equal(document.querySelector('img')?.style.transform,'','專用頭像不能跟著戰鬥方位鏡射');
 await act(async()=>root.render(<ElfAvatar elf={{...elf,skinId:'rey-thunder-dragon-v1'}} kind="head"/>));
 assert.equal(document.querySelector('img')?.getAttribute('src'),'/elf-skins/rey-thunder-dragon-v1.png');
 assert.equal(document.querySelector('img')?.style.transform,'scale(3)','沒有獨立頭像時使用本皮膚裁切參數');
 await act(async()=>root.render(<ElfSkinPicker elf={{...elf,id:'5036',name:'九青',skinId:undefined}} onChange={()=>{throw Error('單款不可替換');}}/>));
 assert.equal(document.querySelector('[aria-label="選擇精靈皮膚"]')?.querySelectorAll('option').length,1);assert.equal(document.querySelector('select')?.disabled,true);
 assert.ok(document.body.textContent?.includes('1 款外觀'));
 console.log('皮膚選擇、原圖回復、序列化、幻化、P1/P2與戰鬥資料保留通過');
}finally{await act(async()=>root.unmount());dom.window.close();}
