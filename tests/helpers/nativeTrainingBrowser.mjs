import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

/** Runs against the real packaged application in an isolated browser/save directory. */
export async function verifyNativeTraining(send,origin){
 const evaluate=async expression=>{
  const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});
  if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description||r.exceptionDetails.text);
  return r.result.value;
 };
 const wait=async expression=>{for(let i=0;i<160;i++){
  if(await evaluate(expression))return;
  await new Promise(r=>setTimeout(r,125));
 }throw Error('新版培養畫面逾時：'+expression+'\n'+await evaluate('document.body.innerText.slice(0,4000)'));};
 const click=label=>evaluate(`(()=>{const scope=document.querySelector('[data-aegis-inscription]')||document;const e=Array.from(scope.querySelectorAll('button')).find(b=>b.textContent.trim()===${JSON.stringify(label)});if(!e)throw Error('找不到按鈕 '+${JSON.stringify(label)});e.click();})()`);
 const select=(label,value)=>evaluate(`(()=>{const e=document.querySelector('[aria-label="${label}"]');Object.getOwnPropertyDescriptor(e instanceof HTMLSelectElement?HTMLSelectElement.prototype:HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event(e instanceof HTMLSelectElement?'change':'input',{bubbles:true}));})()`);
 const shot=async name=>{const out=path.resolve('.seer-cache/native-training-browser');fs.mkdirSync(out,{recursive:true});const r=await send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(out,name+'.png'),Buffer.from(r.data,'base64'));};
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
 await evaluate(`(()=>{localStorage.setItem('seer_shell_preference','aegis');const stats={hp:100,atk:100,def:100,spatk:100,spdef:100,speed:100};for(const side of ['p1','p2']){const e={id:'5053',name:'培養驗收',battleId:'fixture-'+side,level:100,type:'普通',baseStats:stats,calculatedStats:stats,currentHp:100,maxHp:100,skills:[]};const skin={...e,id:'5043',name:'外觀測試',battleId:'skin-'+side};localStorage.setItem('seer_last_used_'+side+'_team',JSON.stringify({team:[e,skin],starterId:e.battleId}));}})()`);
 await send('Page.navigate',{url:origin});
 await wait(`Array.from(document.querySelectorAll('button')).some(b=>b.textContent.trim()==='精靈編成')`);
 await click('精靈編成');await wait(`!!document.querySelector('[data-scene=shared-team]')`);
 await evaluate(`document.querySelector('[data-workspace-slot="p1-0"] > button').click()`);await wait(`!!document.querySelector('[aria-label="精靈等級"]')`);
 await select('精靈等級','120');await select('開戰體力值','50');
 await wait(`JSON.parse(localStorage.getItem('seer_default_elves_overrides')||'{}')['5053']?.level===120`);
 await shot('level-hp');
 await evaluate(`document.querySelector('[aria-label="攻擊個體值"]').closest('details').open=true`);
 await select('攻擊個體值','25');await select('攻擊戰隊加成','5');await select('致命值','2');
 await wait(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].ivs.atk===25`);
 assert.equal(await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].guildBonuses.atk`),5);
 assert.equal(await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].critValue`),2);
 await evaluate(`document.querySelector('[role=tab][title="刻印"]').click()`);
 await wait(`!!document.querySelector('[aria-label="編輯第 1 刻印孔"]')`);
 await evaluate(`document.querySelector('[aria-label="編輯第 1 刻印孔"]').click()`);
 await wait(`!!document.querySelector('[data-aegis-inscription]')`);
 await click('寶石');
 await wait(`!!document.querySelector('[aria-label="刻印寶石種類"]')`);
 const before=await evaluate(`(()=>{const e=JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'];return JSON.stringify(e.inscriptions?.[0]?.stats)})()`);
 await select('刻印寶石種類','1800265');
 assert.ok(await evaluate(`document.querySelector('[aria-label="刻印寶石種類"]').textContent.includes('真實傷害')`),'寶石名稱須繁體');
 await click('外觀');
 await evaluate(`document.querySelector('[aria-label="刻印皮膚"]').open=true`);
 await evaluate(`document.querySelector('[aria-label="刻印皮膚"] button[aria-pressed]').click()`);
 await wait(`document.querySelector('img[alt="已選刻印外觀"]')?.naturalWidth>0`);
 await shot('gem-appearance');await click('確認保存並嵌入');
 await wait(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].inscriptions[0].skinId==='40001'`);
 const after=await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053']`);
 if(before!==undefined)assert.equal(JSON.stringify(after.inscriptions[0].stats),before,'外觀不得改變原刻印數值');
 assert.equal(after.inscriptions[0].gem.id,'1800265');assert.ok(after.inscriptions[0].gem.skillName);
 await evaluate(`document.querySelector('.atr-icon[aria-label="關閉"]').click()`);
 await click('背包全滿血');
 await wait(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].startingHp.value===100`);
 assert.equal(await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].level`),120);
 await evaluate(`document.querySelector('[data-scene=shared-team] > details').open=true`);await select('自由戰場地','destiny');await select('P1自由戰火焰','flame_green');await select('P2自由戰火焰','flame_purple');
 await shot('roster-free-setup');
 await send('Page.navigate',{url:origin});await wait(`Array.from(document.querySelectorAll('button')).some(b=>b.textContent.trim()==='精靈編成')`);
 await click('精靈編成');await wait(`!!document.querySelector('[data-scene=shared-team]')`);
 await evaluate(`document.querySelector('[data-workspace-slot="p1-0"] > button').click()`);await wait(`document.querySelector('[aria-label="精靈等級"]')?.value==='120'`);
 assert.equal(await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].inscriptions[0].skinId`),'40001');
 await evaluate(`document.querySelector('.atr-icon[aria-label="關閉"]').click()`);
 await evaluate(`document.querySelector('[data-workspace-slot="p1-1"] > button').click()`);
 await wait(`!!document.querySelector('[data-aegis-training]')`);
 await evaluate(`document.querySelector('[role=tab][title="外觀"]').click()`);
 await wait(`!!document.querySelector('[aria-label="選擇精靈皮膚"]')`);
 await select('選擇精靈皮膚','gaia-godslayer');
 await wait(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5043']?.skinId==='gaia-godslayer'`);
 await shot('native-elf-appearance');
 await evaluate(`document.querySelector('.atr-icon[aria-label="關閉"]').click()`);
 await wait(`!!document.querySelector('[data-workspace-slot="p1-0"]')`);
 assert.equal(await evaluate(`document.querySelectorAll('[data-workspace-slot]').length`),24,'必須保留雙方各12格出戰與待命位置');
 await evaluate(`document.querySelector('[data-workspace-slot="p1-0"] [aria-label="替換精靈"]').click()`);
 await wait(`!!document.querySelector('[aria-label="選擇替換精靈"] section .grid > button')`);
 await evaluate(`document.querySelector('[aria-label="選擇替換精靈"] section .grid > button').click()`);
 await wait(`!document.querySelector('[aria-label="選擇替換精靈"]')`);
 await evaluate(`document.querySelector('[data-team-side="p1"] [aria-label="保存紀錄"]').click()`);
 await wait(`JSON.parse(localStorage.getItem('seer_last_used_p1_team')).team[0].id!=='5053'`);
 const replaced=await evaluate(`JSON.parse(localStorage.getItem('seer_last_used_p1_team'))`);
 assert.equal(replaced.starterId,replaced.team[0].battleId,'替換首發必須同步更新首發識別碼');
 await shot('native-bag-swap');
 assert.equal(await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5053'].inscriptions[0].skinId`),'40001','換精靈不得清除原精靈培養');
 console.log('正式新版UI：培養120級／開戰體力、寶石綁定、純外觀數值保持、全滿血、自由戰場地火焰與重載保存通過');
 console.log('正式新版背包：原生抽屜換精靈、保存陣容及首發、保留原精靈培養通過');
 console.log('新版功能補齊：原生刻印三頁／繁體字、進階能力調整、獨立外觀頁切換蓋亞皮膚與保存通過');
 await click('精靈編成');await wait(`!!document.querySelector('[data-scene=shared-team]')`);
 await evaluate(`document.querySelector('[data-workspace-slot="p1-1"] > button').click()`);await wait(`!!document.querySelector('[aria-label="編輯精靈"]')`);
 await evaluate(`document.querySelector('[aria-label="編輯精靈"]').click()`);await wait(`!!document.querySelector('[data-aegis-editor] #manual-elf-name')`);
 const workshopName=await evaluate(`document.querySelector('#manual-elf-name').value`);
 const workshopLayout=await evaluate(`(()=>{const f=document.querySelector('.editor-form-panel').getBoundingClientRect(),s=document.querySelector('.editor-draft-summary').getBoundingClientRect();return {form:f.width,summary:s.width,formLeft:f.left,summaryRight:s.right,viewport:innerWidth}})()`);
 if(workshopLayout.viewport>1000){assert.ok(workshopLayout.form>700,'桌面工作坊表單不可被舊版網格壓縮');assert.ok(workshopLayout.summary<300&&workshopLayout.formLeft>=workshopLayout.summaryRight,'草稿摘要應位於窄側欄');}
 await shot('native-workshop');
 for(const [width,height] of [[1280,800],[900,800]]){
  await send('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:false});
  const layout=await evaluate(`(()=>{const box=s=>{const r=document.querySelector(s).getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:r.width}},form=box('.editor-form-panel'),name=box('.editor-basic-name'),path=box('.editor-basic-path'),skin=box('.editor-basic-grid>[aria-label="精靈皮膚"]');return {form,name,path,skin,viewport:innerWidth}})()`);
  assert.ok(layout.form.right<=width+1&&layout.form.left>=0,'工作坊表單不可超出視窗');
  assert.ok(layout.name.width>=200&&layout.path.width>=200,'基本欄位需維持可編輯寬度');
  assert.ok(layout.path.top>=layout.name.bottom&&layout.skin.left>=layout.name.right,'欄位應縱向排列、皮膚預覽獨立於右側');
  await shot(`native-workshop-${width}`);
 }
 await send('Emulation.clearDeviceMetricsOverride');
 await evaluate(`document.querySelector('#tab-blockly-select').click()`);await wait(`!!document.querySelector('[data-effect-workspace]')`);
 await shot('native-workshop-blocks');
 await evaluate(`document.querySelector('#tab-manual-select').click()`);await wait(`!!document.querySelector('#manual-elf-name')`);
 assert.equal(await evaluate(`document.querySelector('#manual-elf-name').value`),workshopName,'切換積木與手動頁必須保留同一份草稿');
 await evaluate(`document.querySelector('#btn-save-manual-elf').click()`);await wait(`!!document.querySelector('[data-scene=shared-team]')`);
 assert.equal(await evaluate(`JSON.parse(localStorage.getItem('seer_default_elves_overrides'))['5043'].skinId`),'gaia-godslayer','完整工作坊保存仍保留皮膚');
 await click('開始對戰／選禁');await wait(`!!document.querySelector('[data-battle-root] [data-battle-controls]')`);
 console.log('完整背包24格／保存與首發、新版培養刻印、工作坊往返與正式進入對戰通過');
}
