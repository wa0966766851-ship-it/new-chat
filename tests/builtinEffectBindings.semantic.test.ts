import assert from 'node:assert/strict';
import {createServer} from 'vite';
const server=await createServer({server:{middlewareMode:true,hmr:false,watch:null},appType:'custom',logLevel:'silent'});
try {
  const {DEFAULT_ELVES:defaults}=await server.ssrLoadModule('/src/data/defaultElvesLoaded.ts');
  const {applySavedSkillCorrections:correct}=await server.ssrLoadModule('/src/data/savedSkillCorrections.ts');
  const {inspectBuiltinEffectBindings:inspect}=await server.ssrLoadModule('/src/data/builtinEffectBindings.ts');
  let count=0;
  for(const source of defaults){
    const saved=correct(structuredClone(source),defaults);
    const rows=inspect(saved,defaults).filter((r:any)=>r.status!=='source-missing');
    assert.ok(rows.every((r:any)=>r.status==='current'),source.name+' 內建效果來源一致');count+=rows.length;
    assert.equal(correct(saved,defaults),saved,'無變動不得重建物件');
  }
  assert.ok(count>=397,'掃描正式載入定義，不只單隻精靈');
  const v1=structuredClone(defaults.find((e:any)=>e.id==='5000'));
  const saved=correct(structuredClone(v1),[v1]);
  saved.battleId='saved-instance';saved.currentHp=42;saved.skills[0].pp=2;saved.evs={atk:252};
  const before=structuredClone(saved),v2=structuredClone(v1);
  v2.soulMark.description+='\n測試用新版本';
  v2.soulMark.kit[0].customText+=' 測試用版本更新';
  v2.skills[0].power+=50;v2.skills[0].description+='\n測試用新技能版本';
  const fixed=correct(saved,[v2]);
  assert.deepEqual(saved,before,'不原地修改存檔');
  assert.deepEqual(fixed.soulMark,v2.soulMark,'已有舊 kit 也必須更新，不能只補缺漏');
  assert.equal(fixed.skills[0].power,v2.skills[0].power);assert.equal(fixed.skills[0].pp,2);
  assert.equal(fixed.battleId,'saved-instance');assert.equal(fixed.currentHp,42);assert.deepEqual(fixed.evs,{atk:252});
  assert.equal(correct(fixed,[v2]),fixed,'更新後冪等');
  const rootOnly=structuredClone(saved);rootOnly.kit=rootOnly.soulMark.kit;delete rootOnly.soulMark.kit;
  assert.deepEqual(correct(rootOnly,[v2]).soulMark.kit,v2.soulMark.kit,'舊編輯器搬到根 kit 不能被誤判成自訂');
  const rootEdited=structuredClone(rootOnly);rootEdited.kit[0].customText+=' 自訂根積木';
  assert.equal(correct(rootEdited,[v2]).soulMark.kit,undefined,'已修改的舊根積木仍須保護');
  assert.deepEqual(correct(rootEdited,[v2]).kit,rootEdited.kit);
  const custom=structuredClone(saved);custom.soulMark.kit[0].customText+=' 我的自訂';
  const customFixed=correct(custom,[v2]);
  assert.deepEqual(customFixed.soulMark,custom.soulMark,'只保護修改過的魂印');
  assert.equal(customFixed.skills[0].power,v2.skills[0].power,'其他未改定義仍更新');
  assert.equal(inspect(customFixed,[v2]).find((r:any)=>r.key==='soul').status,'modified');
  const unknown=structuredClone(saved);delete unknown.builtinEffectBindings;
  assert.deepEqual(correct(unknown,[v2]).soulMark,unknown.soulMark,'無來源的舊 kit 不猜測覆寫');
  assert.equal(inspect(unknown,[v2]).find((r:any)=>r.key==='soul').status,'untracked');
  const disabled=structuredClone(saved);disabled.soulMark.effectMode='none';
  assert.equal(correct(disabled,[v2]).soulMark.effectMode,'none','明確停用視為自訂');
  const emptied=structuredClone(saved);emptied.soulMark.kit=[];emptied.soulMark.effectMode='auto';
  assert.deepEqual(correct(emptied,[v2]).soulMark,emptied.soulMark,'已追蹤的刪除不可被舊補漏規則覆寫');
  const reordered=structuredClone(saved);reordered.skills.reverse();
  assert.equal(correct(reordered,[v2]).skills.find((s:any)=>s.name===v2.skills[0].name).power,v2.skills[0].power,'換技能順序不丟來源');
  const foreign=structuredClone(saved);foreign.id='custom_5000';
  assert.equal(correct(foreign,[v2]),foreign,'自訂身分不得繼承內建版本');
  // 顯示、效果庫、執行解析同一來源，不能讓預覽把技能也當魂印。
  const {soulDefinition}=await server.ssrLoadModule('/src/effects/soulDefinitionSource.ts');
  const {collectEffectPresets}=await server.ssrLoadModule('/src/effects/effectPresets.ts');
  const {effectDefinitionEntries}=await server.ssrLoadModule('/src/battle/effectSources.ts');
  const legacy=structuredClone(v1);delete legacy.soulMark.kit;
  legacy.kit=[{codeId:'test-soul',source:'soulmark',params:{},node:'round_start'}, {codeId:'test-skill',source:'skill',params:{},node:'round_start'}];
  const expected=soulDefinition(legacy).kit;
  assert.equal(expected.length,1);
  assert.deepEqual(collectEffectPresets([legacy]).find((p:any)=>p.id==='5000:soul').definition.kit,expected);
  assert.deepEqual(effectDefinitionEntries(legacy).find((d:any)=>d.soul).kit,expected);
  const acquired=structuredClone(v1);
  acquired.kit=[{codeId:'owner-only',source:'soulmark',params:{},node:'round_start'}];
  acquired.illusion={target:structuredClone(legacy)};
  assert.deepEqual(effectDefinitionEntries(acquired).find((d:any)=>d.soul&&d.acquired).kit,expected,'幻化顯示不能借用原持有者的頂層魂印');
  legacy.soulMark.kit=[];
  assert.deepEqual(soulDefinition(legacy).kit,[],'空 kit 為明確值，不可退回舊頂層');
  const {hasOpponentDamageObserver}=await server.ssrLoadModule('/src/effects/connectedEffects.ts');
  const observer=structuredClone(v1);observer.soulMark.effectMode='kit';delete observer.soulMark.kit;
  observer.skills=[];observer.trait=undefined;observer.alienTraits=undefined;
  const {MIGRATED_STONE_SOUL_KIT}=await server.ssrLoadModule('/src/data/migratedStoneSoulKit.ts');
  observer.kit=[structuredClone(MIGRATED_STONE_SOUL_KIT.kit.find((entry:any)=>entry.node==='on_opponent_damaged'))];
  assert.equal(hasOpponentDamageObserver(observer),true,'事件預篩選也須讀取舊根魂印來源');
  observer.soulMark.kit=[];
  assert.equal(hasOpponentDamageObserver(observer),false,'明確空魂印不可從舊根資料復活觀測器');
  console.log(`✓ ${defaults.length}隻／${count}份來源綁定掃描；跨版本更新、既有 kit、自訂保護、重排、PP／配裝／實例保留、預覽與執行來源一致`);
} finally {await server.close();}
