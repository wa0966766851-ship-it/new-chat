import assert from 'node:assert/strict';
import React, { act } from 'react';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';

const dom = new JSDOM('<div id="root"></div>', { url: 'https://example.test/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, HTMLElement: dom.window.HTMLElement, Element: dom.window.Element, IS_REACT_ACT_ENVIRONMENT: true, requestAnimationFrame: (f: () => void) => setTimeout(f, 0), cancelAnimationFrame: clearTimeout });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const { createRoot } = await import('react-dom/client');
const root = createRoot(document.getElementById('root')!);
const server = await createServer({ server: { middlewareMode: true, hmr: false, watch: null }, appType: 'custom', logLevel: 'silent' });
const button = (text: string) => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === text)!;
const click = async (text: string) => { assert.ok(button(text), text); await act(async () => button(text).click()); };
const waitFor = async (test: () => boolean) => { for (let n = 0; n < 100 && !test(); n++) await act(async () => { await new Promise(r => setTimeout(r, 20)); }); assert.ok(test()); };
try {
  const { DEFAULT_ELVES } = await server.ssrLoadModule('/src/data/defaultElvesLoaded.ts');
  const { createElfUpdateBlueprint, createElfUpdateHandoff } = await server.ssrLoadModule('/src/utils/elfUpdateWorkflow.ts');
  const { parseElfBlueprint } = await server.ssrLoadModule('/src/utils/elfBlueprint.ts');
  const { default: UpdatesPage } = await server.ssrLoadModule('/src/components/UpdatesPage.tsx');
  const elf = DEFAULT_ELVES.find((e: any) => e.id === 'wiki_4937'); assert.ok(elf);
  const before = JSON.stringify(elf);
  const blueprint = createElfUpdateBlueprint(elf), restored = parseElfBlueprint(blueprint).elf;
  assert.equal(restored.id, elf.id); assert.deepEqual(restored.skills.map((s: any) => s.kit), elf.skills.map((s: any) => s.kit));
  assert.deepEqual(restored.soulMark.kit, elf.soulMark.kit);
  const unfinished = { ...elf, skills: [{ ...elf.skills[0], kit: [{ codeId: 'not_registered' }] }] };
  const unfinishedBackup = createElfUpdateBlueprint(unfinished);
  assert.ok(unfinishedBackup.includes('not_registered'), '未完成的原稿也能完整備份或交給 AI 修復');
  assert.throws(() => parseElfBlueprint(unfinishedBackup), '備份不會放寬匯入校驗');
  assert.throws(() => createElfUpdateHandoff(elf, ' '), /填寫/);
  assert.throws(() => createElfUpdateHandoff(elf, 'x'.repeat(4001)), /4000/);
  const handoff = createElfUpdateHandoff(elf, '調整觸發時點，保留原來數值');
  assert.ok(handoff.includes(blueprint)); assert.ok(handoff.includes('P1/P2')); assert.ok(handoff.includes('調整觸發時點'));
  assert.equal(JSON.stringify(elf), before, '產生圖紙與 AI 任務不得改來源');
  localStorage.setItem('seer_api_key', 'TEST_SECRET_DO_NOT_EXPORT'); localStorage.setItem('seer_custom_elves', 'ORIGINAL');
  const storageBefore = JSON.stringify({ ...localStorage });
  let clipboard = '', edited: any, returned = false;
  Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (text: string) => { clipboard = text; } }, configurable: true });
  const render = async (elves = [elf]) => { await act(async () => root.render(<UpdatesPage elves={elves} onBack={() => { returned = true; }} onEditElf={(e: any, tab: string) => { edited = { elf: e, tab }; }} />)); };
  await render();
  assert.ok(document.querySelector('h1')?.textContent?.includes('更新與精靈'));
  assert.ok(document.body.textContent?.includes('精靈更新入口整合'));
  await click('新精靈介紹'); assert.ok(document.body.textContent?.includes('星光·雷納多'));
  await click('查看魂印與技能'); await waitFor(() => !!document.querySelector('[role="dialog"] h2'));
  assert.ok(document.querySelector('[role="dialog"]')?.textContent?.includes('目前使用的精靈資料'));
  // The existing read-only profile closes without touching saved data.
  await act(async () => (document.querySelector('[role="dialog"] button') as HTMLButtonElement).click());
  assert.equal(document.querySelector('[role="dialog"]'), null);
  button('查看魂印與技能').focus(); await click('查看魂印與技能');
  assert.equal(document.activeElement, document.querySelector('[role="dialog"]'));
  await act(async () => { document.activeElement!.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); });
  assert.equal(document.querySelector('[role="dialog"]'), null); assert.equal(document.activeElement, button('查看魂印與技能'));
  await click('修改這隻精靈'); await click('用積木編輯');
  assert.equal(edited.elf.id, elf.id); assert.equal(edited.tab, 'blockly');
  const input = document.querySelector<HTMLTextAreaElement>('#elf-update-request')!;
  await act(async () => { Object.getOwnPropertyDescriptor(dom.window.HTMLTextAreaElement.prototype, 'value')!.set!.call(input, '調整觸發時點'); input.dispatchEvent(new dom.window.Event('input', { bubbles: true })); });
  await click('複製 AI 更新任務'); await waitFor(() => clipboard.includes('調整觸發時點'));
  assert.ok(clipboard.includes('schemaVersion')); assert.ok(!clipboard.includes('TEST_SECRET_DO_NOT_EXPORT'));
  Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => { throw new Error('Permission denied'); } }, configurable: true });
  await click('複製 AI 更新任務'); await waitFor(() => !!document.querySelector('[role="status"]')?.textContent?.includes('下載任務文字檔'));
  // Feed an AI-style edited blueprint through the real file preview and confirm.
  const changed = JSON.parse(blueprint); changed.manualElf.description = 'AI 修改後的草稿';
  const fileInput = document.querySelector<HTMLInputElement>('input[type="file"]')!;
  Object.defineProperty(fileInput, 'files', { value: [{ size: blueprint.length, text: async () => JSON.stringify(changed) }], configurable: true });
  edited = undefined;
  await act(async () => { fileInput.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  await waitFor(() => !!button('確認匯入草稿'));
  assert.equal(edited, undefined, '匯入預覽不得先套用');
  await click('確認匯入草稿'); assert.equal(edited.tab, 'blockly'); assert.equal(edited.elf.description, changed.manualElf.description);
  assert.equal(JSON.stringify({ ...localStorage }), storageBefore, '兩種途徑與匯入均不自動儲存');
  await click('返回首頁'); assert.ok(returned);
  await render([]); assert.equal(button('用積木編輯').disabled, true, '已刪除／尚未載入的精靈不得開空編輯');
  console.log('更新公告、新精靈介紹、積木入口、AI任務、真實圖紙預覽／確認與存檔保護通過。');
} finally { await act(async () => root.unmount()); await server.close(); dom.window.close(); }
